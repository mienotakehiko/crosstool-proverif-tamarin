"""Back ends of cimc. Both printers take the same expanded Case objects
from core.Model, so every rule of the Tamarin model and every block of
a ProVerif encoding are printed from one source (hypothesis Rul)."""
import re
from .core import CimError, free_vars, parse_atom

HDR = '(* Generated by cimc {ver} from {src}. Do not edit. *)'
THDR = '/* Generated by cimc {ver} from {src}. Do not edit. */'


# ================================================================ Tamarin

def t_term(v, fresh=()):
    k = v[0]
    if k == 'num':
        return f"'n{v[1]}'"
    if k == 'const':
        return f"'{v[1]}'"
    if k == 'var':
        return ('~' + v[1]) if v[1] in fresh else v[1]
    if k == 'fun':
        return f"{v[1]}({', '.join(t_term(a, fresh) for a in v[2])})"
    if k == 'pair':
        return f"<{t_term(v[1], fresh)}, {t_term(v[2], fresh)}>"
    raise CimError(v)


def t_ev(e, fresh=()):
    return f"{e[0]}({', '.join(t_term(a, fresh) for a in e[1])})"


def _qvars(atoms, bound=()):
    out = []
    for a in atoms:
        for x in parse_atom(a)[1]:
            if x not in out and x not in bound:
                out.append(x)
    return out


def t_lemma(p, variant):
    k = p['kind']
    attr = ' [use_induction]' if p.get('induction') else ''
    if k == 'phi1':
        prem = p['premise']
        pv = _qvars([prem])
        disj = []
        for i, conj in enumerate(p['conclusion']):
            ev = _qvars(conj, pv)
            ts = [f'#c{i}_{j}' for j in range(len(conj))]
            body = ' & '.join(f'{a}@{t}' for a, t in zip(conj, ts))
            q = ' '.join(ev + ts)
            disj.append(f'(Ex {q}. {body})')
        f = f"All {' '.join(pv)} #k. {prem}@#k ==> " + ' | '.join(disj)
        return f'lemma {p["name"]}{attr}:\n  "{f}"'
    if k == 'phi2':
        atoms = [x.split('@')[0] for x in p['premise']]
        times = ['#' + x.split('@')[1] for x in p['premise']]
        pv = _qvars(atoms)
        body = ' & '.join(f'{a}@{t}' for a, t in zip(atoms, times))
        concl = re.sub(r'\b([a-z]\w*)\b',
                       lambda m: '#' + m.group(1) if '#' + m.group(1) in times else m.group(1),
                       p['conclusion'])
        if p.get('misuse_exception') and variant in ('cl1', 'rb1'):
            who = p['misuse_exception']
            concl += (f' | (Ex x #r. Clone({who},x)@#r)' if variant == 'cl1'
                      else f' | (Ex x y #r. Rollback({who},x,y)@#r)')
        f = f"All {' '.join(pv + times)}. {body} ==> {concl}"
        return f'lemma {p["name"]}{attr}:\n  "{f}"'
    if k == 'phi3':
        ev = p['events']
        pv = _qvars(ev)
        ts = [f'#e{j}' for j in range(len(ev))]
        body = ' & '.join(f'{a}@{t}' for a, t in zip(ev, ts))
        for j, a in enumerate(p.get('absent', [])):
            extra = _qvars([a], pv)
            q = ' '.join(extra + [f'#n{j}'])
            body += f' & not (Ex {q}. {a}@#n{j})'
        f = f"Ex {' '.join(pv + ts)}. {body}"
        return f'lemma {p["name"]}: exists-trace\n  "{f}"'
    raise CimError(k)


def tamarin(m, variant, ver, src):
    """variant: base | cl1 | rb1 | omega"""
    fr = m.fresh
    tid = fr[0]
    L = [THDR.format(ver=ver, src=src),
         f'theory {m.name}_T_{variant}', 'begin', '']
    fl = ', '.join(f"{n}/{a}" + (' [private]' if p else '')
                   for n, (a, p) in m.functions.items())
    L += [f'functions: {fl}', '']
    st = 'St' if variant != 'omega' else '!St'
    thr = f"!Thr_{m.role}({', '.join(fr)})"
    thr0 = f"!Thr_{m.role}({', '.join('~' + x for x in fr)})"
    concl = [thr0, f"{st}(~{tid}, {t_term(m.init, fr)})"]
    concl += [f"!{n}(~{tid}, {t_term(v, fr)})" for n, v in m.persist_vals]
    if variant == 'rb1':
        concl.append(f"!Snap(~{tid}, {t_term(m.init, fr)})")
    if m.publish_val:
        concl.append(f"Out({t_term(m.publish_val, fr)})")
    L += [f'rule Init_{m.role}:',
          f"  [ {', '.join('Fr(~' + x + ')' for x in fr)} ]",
          f"  --[ Start_{m.role}(~{tid}) ]->",
          f"  [ {', '.join(concl)} ]", '']
    for c in m.thread_cases:
        prem = [f"{st}({tid}, {t_term(c.state_in)})", thr]
        if c.inp is not None:
            prem.append(f"In({t_term(c.inp)})")
        acts = [t_ev(e) for e in c.events]
        con = [f"{st}({tid}, {t_term(c.state_out)})"]
        if variant == 'rb1':
            con.append(f"!Snap({tid}, {t_term(c.state_out)})")
        con += [f"Out({t_term(o)})" for o in c.outputs]
        L += [f'rule {c.label}:', f"  [ {', '.join(prem)} ]",
              f"  --[ {', '.join(acts)} ]->", f"  [ {', '.join(con)} ]", '']
    for lk, (en, ea) in zip(m.leaks, m.leak_events):
        L += [f"rule Leak_{en}:", f"  [ {thr} ]",
              f"  --[ {en}({', '.join(t_term(a) for a in ea)}) ]->",
              f"  [ Out({lk['output']}) ]", '']
    for c in m.resp_cases:
        prem = [f"!{n}({t_term(v)})" if False else f"!{n}({tid}, {t_term(v)})"
                for n, v in c.checks]
        prem.append(f"In({t_term(c.inp)})")
        L += [f'rule {c.label}:', f"  [ {', '.join(prem)} ]",
              f"  --[ {', '.join(t_ev(e) for e in c.events)} ]->", '  [ ]', '']
    if variant in ('cl1', 'rb1'):
        L += ['// At most one misuse per thread (Section 4.3).',
              'restriction OneMisuse: "All x #i #j. Misuse(x)@#i & Misuse(x)@#j ==> #i = #j"', '']
    if variant == 'cl1':
        L += ['rule Clone:', f'  [ St({tid}, s) ] --[ Misuse({tid}), Clone({tid}, s) ]-> [ St({tid}, s), St({tid}, s) ]', '']
    if variant == 'rb1':
        L += ['rule Rollback:', f'  [ St({tid}, s), !Snap({tid}, s0) ] --[ Misuse({tid}), Rollback({tid}, s, s0) ]-> [ St({tid}, s0) ]', '']
    for p in m.properties:
        if p.get('misuse_exception') and variant in ('base', 'omega'):
            pass  # same formula as the pure form on these variants
        L += [t_lemma(p, variant), '']
    L.append('end')
    return '\n'.join(L) + '\n'


# ================================================================ ProVerif

def p_term(v, bound):
    """bound: names known in the process (fresh names, pattern vars)."""
    k = v[0]
    if k == 'num':
        return f'n{v[1]}'
    if k == 'const':
        return f'c_{v[1]}'
    if k == 'var':
        return bound.get(v[1], v[1])
    if k == 'fun':
        return f"{v[1]}({', '.join(p_term(a, bound) for a in v[2])})"
    if k == 'pair':
        return f"({p_term(v[1], bound)}, {p_term(v[2], bound)})"
    raise CimError(v)


def p_pattern(v, known, newvars):
    """Input pattern: unknown variables bind (first occurrence), known
    terms and later occurrences become equality tests."""
    k = v[0]
    if k == 'pair':
        return f"({p_pattern(v[1], known, newvars)}, {p_pattern(v[2], known, newvars)})"
    if k == 'var' and v[1] not in known:
        name = 'v_' + v[1]
        known[v[1]] = name
        newvars.append(name)
        return f'{name}: bitstring'
    return '=' + p_term(v, known)


def p_ev(e, b):
    return f"event {e[0]}({', '.join(p_term(a, b) for a in e[1])})"


def p_query(p):
    k = p['kind']
    def vs(atoms):
        return _qvars(atoms)
    if k == 'phi1':
        atoms = [p['premise']] + [a for c in p['conclusion'] for a in c]
        d = ' || '.join(' && '.join(f'event({a})' for a in c) for c in p['conclusion'])
        return f"query {', '.join(x + ':bitstring' for x in vs(atoms))};\n  event({p['premise']}) ==> {d}."
    if k == 'phi2':
        atoms = [x.split('@')[0] for x in p['premise']]
        times = [x.split('@')[1] for x in p['premise']]
        prem = ' && '.join(f'event({a})@{t}' for a, t in zip(atoms, times))
        decl = ', '.join([x + ':bitstring' for x in vs(atoms)] + [t + ':time' for t in times])
        return f"query {decl};\n  {prem} ==> {p['conclusion']}."
    if k == 'phi3':
        # Reachability as the negated query: "false" with a trace = reachable.
        atoms = p['events'] + p.get('absent', [])
        prem = ' && '.join(f'event({a})' for a in p['events'])
        concl = ' || '.join(f'event({a})' for a in p.get('absent', [])) or 'false'
        return f"query {', '.join(x + ':bitstring' for x in vs(atoms))};\n  {prem} ==> {concl}."
    raise CimError(k)


def _case_block(m, c, bound_thread, state_test, tail):
    """One case of a step as a ProVerif process: match the attacker
    input y, test the consumed state x (if any), events, outputs, tail."""
    b = dict(bound_thread)
    newv = []
    parts = []
    if c.inp is not None:
        parts.append(f"let {p_pattern(c.inp, b, newv)} = y in")
    if state_test:
        parts.append(f"if x = {p_term(c.state_in, b)} then")
    body = [p_ev(e, b) for e in c.events] + [f"out(c, {p_term(o, b)})" for o in c.outputs]
    t = tail(c, b)
    if t:
        body.append(t)
    inner = '(' + '; '.join(body) + ')' if body else '0'
    # Each case is closed by its own parentheses: "let p = y in P | Q"
    # would otherwise parse Q inside the scope of the let.
    out = inner
    for part in reversed(parts):
        out = f'{part} ({out})'
    return '(' + out + ')'


def proverif(m, enc, n, ver, src):
    """enc: U | Urb | lin | rep"""
    fr = m.fresh
    tid = fr[0]
    L = [HDR.format(ver=ver, src=src), f'(* {m.name}, encoding {enc}' + (f'({n})' if enc in ('U', 'Urb') else '') + ' *)',
         'free c: channel.']
    cs = sorted(m.all_constants() | {('num', k) for k in range(0, 1)}, key=str)
    lits = sorted(x for x in cs if isinstance(x, str))
    nums = sorted(x[1] for x in cs if isinstance(x, tuple))
    if enc == 'Urb':
        lits = sorted(set(lits) | {'rollback'})
    L.append('const ' + ', '.join([f'c_{x}' for x in lits] + [f'n{k}' for k in nums]) + ': bitstring.')
    for f, (a, p) in m.functions.items():
        L.append(f"fun {f}({', '.join(['bitstring'] * a)}): bitstring" + (' [private].' if p else '.'))
    for e, a in m.event_decl.items():
        L.append(f"event {e}({', '.join(['bitstring'] * a)}).")
    for nme, _ in m.persist_vals:
        L.append(f'table {nme}(bitstring, bitstring).')
    L.append('')
    for p in m.properties:
        if p.get('misuse_exception'):
            continue  # identical to the pure form for ProVerif
        L += [f"(* {p['name']} *)", p_query(p), '']
    bt = {x: x for x in fr}

    # responders: one replicated process per persistent table check
    resp = []
    for c in m.resp_cases:
        b = {}
        newv = []
        pat = p_pattern(c.inp, b, newv)
        gets = ' '.join(f"get {nme}(={p_term(('var', tid), b)}, ={p_term(v, b)}) in" for nme, v in c.checks)
        resp.append(f"(let {pat} = y in ({gets} ({'; '.join(p_ev(e, b) for e in c.events)})))")
    if resp:
        L += ['let Responder() =', '  !in(c, y: bitstring) [precise];',
              '  ( ' + '\n  | '.join(resp) + ' ).', '']

    leak = []
    for lk, (en, ea) in zip(m.leaks, m.leak_events):
        leak.append(f"(in(c, ={tid}); event {en}({', '.join(p_term(a, bt) for a in ea)}); out(c, {lk['output']}))")

    if enc in ('lin', 'rep'):
        so = '!out' if enc == 'rep' else 'out'
        blocks = [_case_block(m, c, bt, True, lambda c, b: f"{so}(st, {p_term(c.state_out, b)})")
                  for c in m.thread_cases]
        steps = [f"{so}(st, {p_term(m.init, bt)})",
                 '!(in(st, x: bitstring) [precise]; in(c, y: bitstring) [precise];\n       ( '
                 + '\n       | '.join(blocks) + ' ))']
        new_st = ' new st: channel;'
    else:
        steps = [_unroll(m, m.init, 0, n, bt, [m.init], enc == 'Urb', 0)]
        new_st = ''
    start = ' '.join(f'new {x}: bitstring;' for x in fr) + new_st
    ins = ' '.join(f"insert {nme}({tid}, {p_term(v, bt)});" for nme, v in m.persist_vals)
    pub = f" out(c, {p_term(m.publish_val, bt)});" if m.publish_val else ''
    L += ['let Thread() =', f'  {start} {ins}{pub}', '  ( ' + '\n  | '.join(steps + leak) + ' ).', '']
    L += ['process', '  ( !Thread() ' + ('| Responder() ' if resp else '') + ')']
    return '\n'.join(L) + '\n'


def _unroll(m, s, d, n, bt, hist, rb, depth_guard):
    """Unrolled state: the state value is known statically. With rb, the
    attacker may request one restoration of an earlier state of the
    thread (the unrolled form of the Tamarin rule Rollback)."""
    if d >= n:
        return '0'
    cases = [c for c in m.thread_cases if c.state_in == s]
    alts = []
    for c in cases:
        def tail(c, b, d=d):
            nxt = _unroll(m, c.state_out, d + 1, n, bt, hist + [c.state_out], rb, depth_guard)
            return None if nxt == '0' else nxt
        alts.append(_case_block(m, c, bt, False, tail))
    if rb:
        for s0 in hist[:-1]:
            nxt = _unroll(m, s0, d, n, bt, hist, False, depth_guard)
            if nxt != '0':
                alts.append(f"(if y = (c_rollback, {p_term(s0, bt)}) then ({nxt}))")
    if not alts:
        return '0'
    return 'in(c, y: bitstring) [precise]; (' + ' | '.join(alts) + ')'
