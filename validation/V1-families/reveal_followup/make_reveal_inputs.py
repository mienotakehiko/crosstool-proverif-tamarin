#!/usr/bin/env python3
"""Write the inputs of the reveal follow-up of series V1.

    python3 -B validation/V1-families/reveal_followup/make_reveal_inputs.py OUTDIR

The follow-up asks whether the reveal alternative of the authentication
property is necessary in the one-time password family. For each of the two
members OTP_N2 and OTP_N3, the script takes the input of series V1 from
validation/V1-families/inputs/renamed/, keeps every line of the model part and
replaces the property list by four properties.

  Auth            property of V1: an acceptance follows a release or a reveal
  Forge           property of V1: an acceptance without a release and without a reveal
  Auth_noreveal   Auth without the reveal alternative
  Forge_noreveal  Forge without the absent reveal event

The script also writes expected_reveal.tsv, the outcomes predicted before the
runs in the notation of series V1 (H for no such trace, W for an existing
trace and N for no outcome). The prediction uses the parameters of the family alone. The
leak outputs the seed, and the hash function of the family is public, so an
attacker who holds the seed derives every password. A login without a release
therefore exists in the standard system and in every system that contains its
traces. The two properties of V1 keep their predictions.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, '..', 'inputs', 'renamed')
MEMBERS = ('otp_n2', 'otp_n3')
MODELS = ('U', 'Urb', 'lin', 'rep', 'base', 'rb', 'cl', 'omega')
SAFE = ('H', 'H', 'H|N', 'H|N', 'H', 'H', 'H', 'H')       # prediction of V1 for Auth and Forge
TRACE = ('W', 'W', 'W|N', 'W', 'W', 'W', 'W', 'W')        # a reveal and a login, with no state reuse

PROPERTIES = '''[[property]]
name       = "Auth"
kind       = "phi1"
premise    = "Acc(I, q)"
conclusion = [["Rel(I, q)"], ["RevealSeed(I)"]]

[[property]]
name   = "Forge"
kind   = "phi3"
events = ["Acc(I, q)"]
absent = ["Rel(I, q)", "RevealSeed(I)"]

[[property]]
name       = "Auth_noreveal"
kind       = "phi1"
premise    = "Acc(I, q)"
conclusion = [["Rel(I, q)"]]

[[property]]
name   = "Forge_noreveal"
kind   = "phi3"
events = ["Acc(I, q)"]
absent = ["Rel(I, q)"]
'''


def derive(member):
    """Return the name and the text of the follow-up input of one member."""
    with open(os.path.join(SOURCE, member + '.toml'), encoding='utf-8') as handle:
        lines = handle.read().split('\n')
    old = member.upper()
    new = old + '_REVEAL'
    first = lines.index('[[property]]')
    model = lines[:first]
    if not model[0].startswith('# Generated by make_family.py') or model.count(f'name = "{old}"') != 1:
        sys.exit(f'unexpected input of series V1: {member}.toml')
    model[0] = (f'# Generated by make_reveal_inputs.py from {member}.toml of series V1. '
                'Edit the script, not this file.')
    model[model.index(f'name = "{old}"')] = f'name = "{new}"'
    return new, '\n'.join(model) + '\n' + PROPERTIES


def main():
    outdir = sys.argv[1] if len(sys.argv) > 1 else 'inputs'
    os.makedirs(outdir, exist_ok=True)
    rows = ['# set\tproperty\tmodel\tallowed outcomes (predicted before the runs)']
    for member in MEMBERS:
        name, text = derive(member)
        with open(os.path.join(outdir, name.lower() + '.toml'), 'w', encoding='utf-8') as handle:
            handle.write(text)
        table = {'Auth': SAFE, 'Forge': SAFE, 'Auth_noreveal': TRACE, 'Forge_noreveal': TRACE}
        for prop, cells in table.items():
            rows.extend(f'{name.lower()}\t{prop}\t{model}\t{allowed}' for model, allowed in zip(MODELS, cells))
    with open(os.path.join(outdir, 'expected_reveal.tsv'), 'w', encoding='utf-8') as handle:
        handle.write('\n'.join(rows) + '\n')
    print(f'wrote {len(MEMBERS)} CIM files and expected_reveal.tsv to {outdir}')


if __name__ == '__main__':
    main()
