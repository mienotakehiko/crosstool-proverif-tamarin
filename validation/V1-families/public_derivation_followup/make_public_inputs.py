#!/usr/bin/env python3
"""Write the inputs of the public-derivation follow-up of series V1.

    python3 -B validation/V1-families/public_derivation_followup/make_public_inputs.py OUTDIR

The signer families of series V1 derive the starting values of their chains
with a private function of the seed. An attacker who holds the seed cannot
apply this function, so the reveal alternative of the unforgeability property
is never needed there. This follow-up declares the function public in two
members, LM-OTS(2,1) and LMS(1,2), so that a revealed seed yields every chain
value. For each member, the script takes the input of series V1, removes the
attribute "private" from the declaration of the function prf, keeps every
other line of the model part and every property, and appends two properties.

  LM-OTS(2,1)  LS1_unforge_noreveal  LS1_unforge without the reveal alternative
               forge_noreveal        forge without the absent reveal event
  LMS(1,2)     LS1_noreveal          LS1 without the reveal alternative
               LS3_forge_noreveal    LS3_forge without the absent reveal event

The script also writes expected_public.tsv, the outcomes predicted before the
runs in the notation of series V1 (H for no such trace, W for an existing
trace and N for no outcome). The properties of V1 keep the predictions of V1,
because every use of a revealed seed comes with the reveal event, which these
properties name. The two new properties have a trace on every model. The leak
outputs the seed, the attacker applies the public function to it and forges a
signature without any signing step, so no state reuse is involved.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
INPUTS = os.path.join(HERE, '..', 'inputs')
MODELS = ('U', 'Urb', 'lin', 'rep', 'base', 'rb', 'cl', 'omega')
TRACE = ('W', 'W', 'W|N', 'W', 'W', 'W', 'W', 'W')        # a reveal and an acceptance, with no state reuse

MEMBERS = {
    'lmots_w2m1': {
        'source': os.path.join('fixed', 'lmots_w2m1.toml'),
        'private': '  { name = "prf", arity = 2, private = true },',
        'public': '  { name = "prf", arity = 2 },',
        'new': ('LS1_unforge_noreveal', 'forge_noreveal'),
        'properties': '''
[[property]]
name       = "LS1_unforge_noreveal"
kind       = "phi1"
premise    = "Accept(I, a1)"
conclusion = [["Sign(I, a1)"]]

[[property]]
name   = "forge_noreveal"
kind   = "phi3"
events = ["Accept(I, a1)"]
absent = ["Sign(I, a1)"]
''',
    },
    'lms_h1w2': {
        'source': os.path.join('renamed', 'lms_h1w2.toml'),
        'private': '  { name = "prf", arity = 3, private = true },',
        'public': '  { name = "prf", arity = 3 },',
        'new': ('LS1_noreveal', 'LS3_forge_noreveal'),
        'properties': '''
[[property]]
name       = "LS1_noreveal"
kind       = "phi1"
premise    = "Accept(I, q, a)"
conclusion = [["Sign(I, q, a)"]]

[[property]]
name   = "LS3_forge_noreveal"
kind   = "phi3"
events = ["Accept(I, q, a)"]
absent = ["Sign(I, q, a)"]
''',
    },
}


def derive(member):
    """Return the name and the text of the follow-up input of one member."""
    spec = MEMBERS[member]
    with open(os.path.join(INPUTS, spec['source']), encoding='utf-8') as handle:
        text = handle.read()
    lines = text.rstrip('\n').split('\n')
    old = member.upper()
    new = old + '_PUB'
    if (not lines[0].startswith('# Generated by make_family.py') or lines.count(f'name = "{old}"') != 1
            or lines.count(spec['private']) != 1 or text.count('private') != 1):
        sys.exit(f'unexpected input of series V1: {spec["source"]}')
    lines[0] = (f'# Generated by make_public_inputs.py from {member}.toml of series V1. '
                'Edit the script, not this file.')
    lines[lines.index(f'name = "{old}"')] = f'name = "{new}"'
    lines[lines.index(spec['private'])] = spec['public']
    return new, '\n'.join(lines) + '\n' + spec['properties']


def main():
    outdir = sys.argv[1] if len(sys.argv) > 1 else 'inputs'
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(INPUTS, 'fixed', 'expected_e1.tsv'), encoding='utf-8') as handle:
        v1_rows = [line.split('\t') for line in handle.read().split('\n') if line and not line.startswith('#')]
    rows = ['# set\tproperty\tmodel\tallowed outcomes (predicted before the runs)']
    for member, spec in MEMBERS.items():
        name, text = derive(member)
        with open(os.path.join(outdir, name.lower() + '.toml'), 'w', encoding='utf-8') as handle:
            handle.write(text)
        kept = [row for row in v1_rows if row[0] == member]
        if not kept:
            sys.exit(f'no prediction of series V1 for {member}')
        rows.extend('\t'.join([name.lower()] + row[1:]) for row in kept)
        for prop in spec['new']:
            rows.extend(f'{name.lower()}\t{prop}\t{model}\t{allowed}' for model, allowed in zip(MODELS, TRACE))
    with open(os.path.join(outdir, 'expected_public.tsv'), 'w', encoding='utf-8') as handle:
        handle.write('\n'.join(rows) + '\n')
    print(f'wrote {len(MEMBERS)} CIM files and expected_public.tsv to {outdir}')


if __name__ == '__main__':
    main()
