#!/usr/bin/env python3
"""Write the CIM inputs of the three parameterized families of series V1.

    python3 -B make_family.py OUTDIR

  LMOTS_W<w>M<m>  one-time signer with digits of w bits, m message digits and
                  one checksum chain (w = 2 and m = 1 give the signer of the paper)
  LMS_H<h>W<w>    Merkle-tree signer with 2^h leaves over LMOTS_W<w>M1
                  (h = 1 and w = 2 give the signer of the paper)
  OTP_N<n>        one-time passwords from a hash chain, with a release counter
                  and an acceptance counter as the state

The script writes one TOML file per parameter choice and the table family.tsv,
which lists the name, the family, the parameters and the declared update bound
of every member.
"""
import os
import sys

HEADER = '# Generated by make_family.py (experiment E1). Edit the script, not this file.\n'


def lmots(w, m):
    top = 2 ** w - 1                      # largest digit
    ktop = m * top                        # length of the checksum chain
    digits = [f'a{i}' for i in range(1, m + 1)]
    name = f'LMOTS_W{w}M{m}'
    cks = f'{ktop}' + ''.join(f' - {d}' for d in digits)
    dom = ', '.join(f'{d} = {list(range(top + 1))}' for d in digits)
    chains = ', '.join(f"up(I, 'm{i}', {top}, prf(sd, 'm{i}'))" for i in range(1, m + 1))
    sig = ', '.join(f"up(I, 'm{i}', a{i}, prf(sd, 'm{i}'))" for i in range(1, m + 1))
    ver = ', '.join(f"up(I, 'm{i}', {top} - a{i}, s{i})" for i in range(1, m + 1))
    args = ', '.join(digits)
    svars = ', '.join(f's{i}' for i in range(1, m + 1))
    # checksum digit of the verifier, whose chain 'k' continues from position ktop - sum
    kver = ' + '.join(digits)
    text = f'''{HEADER}name = "{name}"

[meta]
parameters = "w = {w}, message digits = {m}, checksum chain of length {ktop}"

[signature]
functions = [
  {{ name = "ch",  arity = 3 }},
  {{ name = "prf", arity = 2, private = true }},
]

[macros]
up = {{ params = ["I", "d", "n", "t"], body = "t if n == 0 else ch(I, d, up(I, d, n - 1, t))" }}
pk = {{ params = ["I", "sd"], body = "tup({chains}, up(I, 'k', {ktop}, prf(sd, 'k')))" }}

[thread]
role    = "Signer"
fresh   = ["I", "sd"]
state   = ["q"]
init    = {{ q = 0 }}
bound   = 1
publish = "tup(I, pk(I, sd))"
persist = [ {{ name = "Pk", term = "pk(I, sd)" }} ]

[[thread.leak]]
event  = "RevealSeed(I)"
output = "sd"

[[thread.step]]
name    = "Sign"
domain  = {{ q = [0], {dom} }}
input   = "tup('sign', {args})"
update  = {{ q = "q + 1" }}
events  = ["Sign(I, {args})"]
outputs = ["tup(I, {args}, {sig}, up(I, 'k', {cks}, prf(sd, 'k')))"]

[[responder]]
name   = "Verify"
domain = {{ {dom} }}
input  = "tup(I, {args}, {svars}, sk)"
check  = {{ Pk = "tup({ver}, up(I, 'k', {kver}, sk))" }}
events = ["Accept(I, {args})"]

[[property]]
name   = "exec_accept"
kind   = "phi3"
events = ["Sign(I, {args})", "Accept(I, {args})"]
absent = ["RevealSeed(I)"]

[[property]]
name       = "LS1_unforge"
kind       = "phi1"
premise    = "Accept(I, {args})"
conclusion = [["Sign(I, {args})"], ["RevealSeed(I)"]]

[[property]]
name   = "forge"
kind   = "phi3"
events = ["Accept(I, {args})"]
absent = ["Sign(I, {args})", "RevealSeed(I)"]
'''
    return name, text, f'w={w};m={m}', 1


def lms(h, w):
    top = 2 ** w - 1
    leaves = 2 ** h
    name = f'LMS_H{h}W{w}'

    def node(level, index):
        if level == 0:
            return f'leafpk(I, sd, {index})'
        return f'hl(I, {node(level - 1, 2 * index)}, {node(level - 1, 2 * index + 1)})'

    def path(q):                       # siblings from the leaf level upwards
        out = []
        for level in range(h):
            out.append(node(level, (q >> level) ^ 1))
        return out

    def by_leaf(render):               # conditional expression over the leaf index q
        expr = render(leaves - 1)
        for q in range(leaves - 2, -1, -1):
            expr = f'{render(q)} if q == {q} else {expr}'
        return expr

    sibs = ', '.join(f's{level}' for level in range(h))
    out_expr = by_leaf(lambda q: "tup(I, q, a, up(I, 'm', a, prf(sd, q, 'm')), up(I, 'k', "
                       + f"{top} - a, prf(sd, q, 'k')), " + ', '.join(path(q)) + ')')

    def rebuild(q):
        cur = f"tup(up(I, 'm', {top} - a, sm), up(I, 'k', a, sk))"
        for level in range(h):
            cur = f'hl(I, s{level}, {cur})' if (q >> level) & 1 else f'hl(I, {cur}, s{level})'
        return cur

    text = f'''{HEADER}name = "{name}"

[meta]
parameters = "h = {h} ({leaves} leaves), w = {w}, p = 2"

[signature]
functions = [
  {{ name = "ch",  arity = 3 }},
  {{ name = "prf", arity = 3, private = true }},
  {{ name = "hl",  arity = 3 }},
]

[macros]
up     = {{ params = ["I", "d", "n", "t"], body = "t if n == 0 else ch(I, d, up(I, d, n - 1, t))" }}
leafpk = {{ params = ["I", "sd", "q"], body = "tup(up(I, 'm', {top}, prf(sd, q, 'm')), up(I, 'k', {top}, prf(sd, q, 'k')))" }}
root   = {{ params = ["I", "sd"], body = "{node(h, 0)}" }}

[thread]
role    = "Signer"
fresh   = ["I", "sd"]
state   = ["q"]
init    = {{ q = 0 }}
bound   = {leaves}
publish = "tup(I, root(I, sd))"
persist = [ {{ name = "Root", term = "root(I, sd)" }} ]

[[thread.leak]]
event  = "RevealSeed(I)"
output = "sd"

[[thread.step]]
name    = "Sign"
domain  = {{ q = {list(range(leaves))}, a = {list(range(top + 1))} }}
input   = "tup('sign', a)"
update  = {{ q = "q + 1" }}
events  = ["Sign(I, q, a)"]
outputs = ["{out_expr}"]

[[responder]]
name   = "Verify"
domain = {{ q = {list(range(leaves))}, a = {list(range(top + 1))} }}
input  = "tup(I, q, a, sm, sk, {sibs})"
check  = {{ Root = "{by_leaf(rebuild)}" }}
events = ["Accept(I, q, a)"]

[[property]]
name   = "exec"
kind   = "phi3"
events = ["Sign(I, q, a)", "Accept(I, q, a)"]
absent = ["RevealSeed(I)"]

[[property]]
name       = "LS4_pure"
kind       = "phi2"
premise    = ["Sign(I, q, a1)@i", "Sign(I, q, a2)@j"]
conclusion = "i = j"
induction  = true

[[property]]
name       = "LS4"
kind       = "phi2"
premise    = ["Sign(I, q, a1)@i", "Sign(I, q, a2)@j"]
conclusion = "i = j"
induction  = true
misuse_exception = "I"

[[property]]
name       = "LS1"
kind       = "phi1"
premise    = "Accept(I, q, a)"
conclusion = [["Sign(I, q, a)"], ["RevealSeed(I)"]]

[[property]]
name   = "LS3_forge"
kind   = "phi3"
events = ["Accept(I, q, a)"]
absent = ["Sign(I, q, a)", "RevealSeed(I)"]
'''
    return name, text, f'h={h};w={w}', leaves


def otp(n):
    name = f'OTP_N{n}'
    text = f'''{HEADER}# Hash-chain one-time passwords. The seed sd defines the passwords
# x_j = h^(n-j)(sd) for j = 0 .. n-1 and the public anchor h^(n+1)(sd); the
# seed itself leaves the thread only through the leak. The state has two
# counters: c counts the passwords that the user has released, v counts the
# logins that the verifier has accepted. A login with counter v needs x_v.
name = "{name}"

[meta]
parameters = "chain length n = {n}, state (c, v)"

[signature]
functions = [
  {{ name = "h", arity = 2 }},
]

[macros]
up = {{ params = ["I", "n", "t"], body = "t if n == 0 else h(I, up(I, n - 1, t))" }}

[thread]
role    = "User"
fresh   = ["I", "sd"]
state   = ["c", "v"]
init    = {{ c = 0, v = 0 }}
bound   = {2 * n}
publish = "tup(I, up(I, {n + 1}, sd))"

[[thread.leak]]
event  = "RevealSeed(I)"
output = "sd"

[[thread.step]]
name    = "Release"
domain  = {{ c = {list(range(n))}, v = {list(range(n + 1))} }}
input   = "tup('rel', c)"
update  = {{ c = "c + 1" }}
events  = ["Rel(I, c)"]
outputs = ["tup(I, c, up(I, {n} - c, sd))"]

[[thread.step]]
name    = "Login"
domain  = {{ c = {list(range(n + 1))}, v = {list(range(n))} }}
input   = "tup('login', up(I, {n} - v, sd))"
update  = {{ v = "v + 1" }}
events  = ["Acc(I, v)"]

[[property]]
name   = "exec"
kind   = "phi3"
events = ["Rel(I, q)", "Acc(I, q)"]
absent = ["RevealSeed(I)"]

[[property]]
name       = "NoReplay_pure"
kind       = "phi2"
premise    = ["Acc(I, q)@i", "Acc(I, q)@j"]
conclusion = "i = j"
induction  = true

[[property]]
name       = "NoReplay"
kind       = "phi2"
premise    = ["Acc(I, q)@i", "Acc(I, q)@j"]
conclusion = "i = j"
induction  = true
misuse_exception = "I"

[[property]]
name       = "Auth"
kind       = "phi1"
premise    = "Acc(I, q)"
conclusion = [["Rel(I, q)"], ["RevealSeed(I)"]]

[[property]]
name   = "Forge"
kind   = "phi3"
events = ["Acc(I, q)"]
absent = ["Rel(I, q)", "RevealSeed(I)"]
'''
    return name, text, f'n={n}', 2 * n


GRID = ([lmots(w, 1) for w in (1, 2, 3, 4)] + [lmots(2, 2)]
        + [lms(1, 1), lms(1, 2), lms(2, 1), lms(2, 2), lms(3, 1)]
        + [otp(2), otp(3)])


# Outcomes predicted before the runs. H means no such trace, W means that such a
# trace exists, and N means no outcome. The columns are U, Urb, lin, rep, base, rb,
# cl and omega, and "-" marks a model without this property. The option --expected
# of xcheck.py reports every deviation.
MODELS = ('U', 'Urb', 'lin', 'rep', 'base', 'rb', 'cl', 'omega')
REACH = ('W', 'W', 'W|N', 'W', 'W', 'W', 'W', 'W')
SAFE = ('H', 'H', 'H|N', 'H|N', 'H', 'H', 'H', 'H')           # holds even with a reused state value


def forgeable(w, m):
    """Decide whether two signatures of one key yield a signature on a third message.

    A signature on the digits a reveals position a_i of message chain i and
    position m*top - sum(a) of the checksum chain, and the attacker moves forward
    on every chain. From the signatures on a and b, the digits c verify if
    c_i >= min(a_i, b_i) for every i and sum(c) <= max(sum(a), sum(b)). With
    one digit of one bit (w = 1 and m = 1), the two signatures already cover
    both messages, so no third message exists."""
    import itertools
    top = 2 ** w - 1
    space = list(itertools.product(range(top + 1), repeat=m))
    for a, b in itertools.combinations(space, 2):
        for c in space:
            if c not in (a, b) and all(x >= min(y, z) for x, y, z in zip(c, a, b)) \
                    and sum(c) <= max(sum(a), sum(b)):
                return True
    return False


def expected(name, family, w=None, m=1):
    """Return the predicted outcome of every property on every model of one family member."""
    if family == 'LMOTS':
        # With one signing step, the unrolling with rollback has depth one and equals U.
        reuse = ('H', 'H', 'H|N', 'W', 'H', 'W', 'W', 'W') if forgeable(w, m) else SAFE
        return {'exec_accept': REACH, 'LS1_unforge': reuse, 'forge': reuse}
    if family == 'LMS':
        twice = ('H', 'W', 'H|N', 'W', 'H', 'W', 'W', 'W')    # a leaf signs twice after one misuse
        forge = twice if forgeable(w, 1) else SAFE
        return {'exec': REACH, 'LS4_pure': twice, 'LS4': ('-', '-', '-', '-', 'H', 'H', 'H', 'W'),
                'LS1': forge, 'LS3_forge': forge}
    if family == 'OTP':
        # A replay needs a reused state, and a login always follows the release of its password.
        return {'exec': REACH, 'NoReplay_pure': ('H', 'W', 'H|N', 'W', 'H', 'W', 'W', 'W'),
                'NoReplay': ('-', '-', '-', '-', 'H', 'H', 'H', 'W'), 'Auth': SAFE, 'Forge': SAFE}
    raise ValueError(family)


def parameters(params):
    return {key: int(value) for key, value in (item.split('=') for item in params.split(';'))}


def main():
    outdir = sys.argv[1] if len(sys.argv) > 1 else 'cims'
    os.makedirs(outdir, exist_ok=True)
    rows = ['name\tfamily\tparameters\tbound']
    for name, text, params, bound in GRID:
        with open(os.path.join(outdir, name.lower() + '.toml'), 'w', encoding='utf-8') as handle:
            handle.write(text)
        rows.append(f"{name}\t{name.split('_')[0]}\t{params}\t{bound}")
    with open(os.path.join(outdir, 'family.tsv'), 'w', encoding='utf-8') as handle:
        handle.write('\n'.join(rows) + '\n')
    lines = ['# set\tproperty\tmodel\tallowed outcomes (predicted before the runs)']
    for name, _, params, _ in GRID:
        values = parameters(params)
        table = expected(name, name.split('_')[0], values.get('w'), values.get('m', 1))
        for prop, cells in table.items():
            for model, allowed in zip(MODELS, cells):
                if allowed != '-':
                    lines.append(f'{name.lower()}\t{prop}\t{model}\t{allowed}')
    with open(os.path.join(outdir, 'expected_e1.tsv'), 'w', encoding='utf-8') as handle:
        handle.write('\n'.join(lines) + '\n')
    print(f'wrote {len(GRID)} CIM files, family.tsv and expected_e1.tsv to {outdir}')


if __name__ == '__main__':
    main()
