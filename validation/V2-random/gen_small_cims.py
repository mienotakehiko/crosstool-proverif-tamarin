#!/usr/bin/env python3
"""Write small random Common Iterative Models for series V2.

    python3 -B gen_small_cims.py OUTDIR [--count 200] [--seed 20261116] [--verify MANIFEST]
        [--cimc-012]

Every model has one thread with a numeric state q, one to three step kinds,
an optional public verifier, a seed leak and three to six properties of the
classes Phi1, Phi2 and Phi3. The models stay inside the fragment of the
generator, which requires a linear numeric state, finite domains, at most one
attacker input per step and disjoint dispatch at every state. The random
choices decide

  * the number of state values (1 to 3) and the chain length (1 or 2),
  * which chain position each step releases, as a function of the state
    and of an attacker digit,
  * which chain position the verifier expects,
  * whether a second step kind exists and which states enable it,
  * whether one state advances by a step without input. Such a step is the
    only case of its state, because it accepts every message.

Many of the properties fail on purpose, because a step may release the value
that the verifier accepts before any matching event. The series predicts no
verdict. It checks that the verdicts of the eight generated models never form
a pair that the inclusion chain excludes (xcheck.py).

The same seed always writes the same files. The table manifest.tsv lists them
with their SHA-256 hashes, so a run can fix its inputs before any prover
starts. The option --verify compares the written files with a reference
manifest, for example manifest_20261116.tsv next to this script (200 models,
seed 20261116), and ends with status 1 if a file differs. The option
--cimc-012 selects a name for the responder variable that cimc 0.1.2 accepts.
"""
import argparse
import hashlib
import os
import random

HEADER = "# Generated by gen_small_cims.py (experiment E2), seed {seed}, index {index}. Do not edit.\n"


def release_term(rng, chain_length, digit):
    """Return a term that a step outputs. The term may depend on the state q and the digit a."""
    start = rng.choice(["prf(sd, 'a')", "prf(sd, 'b')"])
    choices = [f"up(I, {rng.randint(0, chain_length)}, {start})"]
    if digit:
        choices.append(f"up(I, a, {start})")
        choices.append(f"up(I, {chain_length} - a, {start})")
    if chain_length >= 1:
        choices.append(f"up(I, q, {start})" if rng.random() < 0.3 else choices[0])
    return rng.choice(choices)


def model(rng, seed, index, *, cimc_012=False):
    name = f"R{index:03d}"
    states = rng.randint(1, 3)                     # q takes the values 0 .. states
    chain = rng.randint(1, 2)
    digit1 = rng.random() < 0.6                    # step kind 1 reads a digit a in {0, 1}
    two_kinds = rng.random() < 0.5
    verifier = rng.random() < 0.85
    vdigit = verifier and digit1 and rng.random() < 0.5
    q_all = list(range(states))
    # One state may advance without input, and no other step kind uses that state.
    silent = rng.choice(q_all) if (states >= 2 and rng.random() < 0.25) else None
    q_in = [q for q in q_all if q != silent]
    args1 = "I, q, a" if digit1 else "I, q"
    out1 = release_term(rng, min(chain, 1) if not digit1 else chain, digit1)
    lines = [HEADER.format(seed=seed, index=index), f'name = "{name}"', "", "[meta]",
             f'parameters = "states = {states}, chain = {chain}, digit = {int(digit1)}, kinds = {1 + int(two_kinds)}, '
             f'verifier = {int(verifier)}, silent = {"none" if silent is None else silent}"',
             "", "[signature]", "functions = [", '  { name = "h",   arity = 2 },',
             '  { name = "prf", arity = 2, private = true },', "]", "", "[macros]",
             'up = { params = ["I", "n", "t"], body = "t if n == 0 else h(I, up(I, n - 1, t))" }', "",
             "[thread]", 'role    = "Actor"', 'fresh   = ["I", "sd"]', 'state   = ["q"]', "init    = { q = 0 }",
             f"bound   = {states}", f'publish = "tup(I, up(I, {chain}, prf(sd, \'a\')))"',
             f'persist = [ {{ name = "Pk", term = "up(I, {chain}, prf(sd, \'a\'))" }} ]', "",
             "[[thread.leak]]", 'event  = "RevealSeed(I)"', 'output = "sd"', "",
             "[[thread.step]]", 'name    = "StepA"',
             "domain  = { q = %s%s }" % (q_in, ", a = [0, 1]" if digit1 else ""),
             'input   = "%s"' % ("tup('sa', a)" if digit1 else "tup('sa', q)"),
             'update  = { q = "q + 1" }', f'events  = ["EvA({args1})"]',
             f'outputs = ["tup({args1}, {out1})"]', ""]
    if silent is not None:
        out3 = release_term(rng, chain, False)
        lines += ["[[thread.step]]", 'name    = "Tick"', f"domain  = {{ q = [{silent}] }}",
                  'update  = { q = "q + 1" }', 'events  = ["EvT(I, q)"]', f'outputs = ["tup(I, q, {out3})"]', ""]
    if two_kinds:
        enabled = sorted(rng.sample(q_in, rng.randint(1, len(q_in))))
        out2 = release_term(rng, chain, False)
        lines += ["[[thread.step]]", 'name    = "StepB"', f"domain  = {{ q = {enabled} }}",
                  "input   = \"tup('sb', q)\"", 'update  = { q = "q + 1" }', 'events  = ["EvB(I, q)"]',
                  f'outputs = ["tup(I, q, {out2})"]', ""]
    if verifier:
        expect = rng.randint(0, chain)
        value = "recv_value" if cimc_012 else "x"
        if vdigit:
            check = rng.choice([f"up(I, {chain} - a, {value})", f"up(I, a, {value})",
                                f"up(I, {expect}, {value})"])
            lines += ["[[responder]]", 'name   = "Verify"', "domain = { a = [0, 1] }", f'input  = "tup(I, a, {value})"',
                      f'check  = {{ Pk = "{check}" }}', 'events = ["Acc(I, a)"]', ""]
        else:
            lines += ["[[responder]]", 'name   = "Verify"', f'input  = "tup(I, {value})"',
                      f'check  = {{ Pk = "up(I, {expect}, {value})" }}', 'events = ["Acc(I)"]', ""]
    acc = "Acc(I, a)" if vdigit else "Acc(I)"
    # properties
    lines += ["[[property]]", 'name   = "reachA"', 'kind   = "phi3"', f'events = ["EvA({args1})"]',
              'absent = ["RevealSeed(I)"]', ""]
    if digit1:
        lines += ["[[property]]", 'name       = "uniqA"', 'kind       = "phi2"',
                  'premise    = ["EvA(I, q, a1)@i", "EvA(I, q, a2)@j"]', 'conclusion = "i = j"', "induction  = true", ""]
    else:
        lines += ["[[property]]", 'name       = "uniqA"', 'kind       = "phi2"',
                  'premise    = ["EvA(I, q)@i", "EvA(I, q)@j"]', 'conclusion = "i = j"', "induction  = true", ""]
    if two_kinds:
        lines += ["[[property]]", 'name   = "reachB"', 'kind   = "phi3"', 'events = ["EvB(I, q)"]', ""]
    if silent is not None:
        lines += ["[[property]]", 'name   = "reachT"', 'kind   = "phi3"', 'events = ["EvT(I, q)"]',
                  'absent = ["RevealSeed(I)"]', ""]
    if verifier:
        # with a shared digit the verifier's digit must equal the signer's digit
        witness = "EvA(I, q, a)" if (digit1 and vdigit) else ("EvA(I, q, b)" if digit1 else "EvA(I, q)")
        lines += ["[[property]]", 'name       = "auth"', 'kind       = "phi1"', f'premise    = "{acc}"',
                  f'conclusion = [["{witness}"], ["RevealSeed(I)"]]', "",
                  "[[property]]", 'name   = "accept"', 'kind   = "phi3"', f'events = ["{acc}"]',
                  'absent = ["RevealSeed(I)"]', "",
                  "[[property]]", 'name   = "forge"', 'kind   = "phi3"', f'events = ["{acc}"]',
                  f'absent = ["{witness}", "RevealSeed(I)"]', ""]
    return name, "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("outdir")
    parser.add_argument("--count", type=int, default=200)
    parser.add_argument("--seed", type=int, default=20261116)
    parser.add_argument("--verify", help="reference manifest to compare with")
    parser.add_argument("--cimc-012", action="store_true",
                        help="use recv_value instead of the reserved responder variable x")
    args = parser.parse_args()
    os.makedirs(args.outdir, exist_ok=True)
    rng = random.Random(args.seed)
    rows = ["file\tsha256"]
    for index in range(args.count):
        name, text = model(rng, args.seed, index, cimc_012=args.cimc_012)
        path = os.path.join(args.outdir, name.lower() + ".toml")
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(text)
        rows.append(f"{name.lower()}.toml\t{hashlib.sha256(text.encode()).hexdigest()}")
    with open(os.path.join(args.outdir, "manifest.tsv"), "w", encoding="utf-8") as handle:
        handle.write("\n".join(rows) + "\n")
    print(f"wrote {args.count} models and manifest.tsv to {args.outdir} (seed {args.seed})")
    if args.verify:
        with open(args.verify, encoding="utf-8") as handle:
            reference = handle.read().splitlines()
        if reference != rows:
            differing = sum(1 for a, b in zip(reference, rows) if a != b) + abs(len(reference) - len(rows))
            print(f"the files differ from {args.verify} in {differing} line(s)")
            raise SystemExit(1)
        print(f"the files equal the reference manifest {args.verify}")


if __name__ == "__main__":
    main()
